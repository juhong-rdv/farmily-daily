def full_regions():
    """수집 스크립트용: 격자(nx,ny)·일조 관측소 후보·중기예보 지점 후보까지 계산한 전체 목록."""
    out = []
    for sc, short, items in SIDO:
        for i, (name, lat, lon) in enumerate(items, 1):
            nx, ny = latlon_to_grid(lat, lon)
            asos = sorted(ASOS, key=lambda s: haversine(lat, lon, s[2], s[3]))[:3]
            mid = sorted(MID, key=lambda m: haversine(lat, lon, m[2], m[3]))[:2]
            out.append({"code": "%s%02d" % (sc, i), "sido": short, "name": name, "lat": lat, "lon": lon, "nx": nx, "ny": ny,
                "asos": [{"id": s[0], "name": s[1], "km": round(haversine(lat, lon, s[2], s[3]))} for s in asos],
                "mid": [{"id": m[0], "name": m[1]} for m in mid]})
    return out

